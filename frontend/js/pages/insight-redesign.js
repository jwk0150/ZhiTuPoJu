  // ===== 渲染：核心技能掌握度雷达图 =====
  // 取该岗位最重要的 6 项技能：4 项核心（mod）+ 2 项新兴（up）
  // 掌握度评分基于技能名 hash 稳定生成（60~96），保证同一技能每次一致
  function getRadarAxes() {
    const pf = getProfile(STATE.jobId);
    const mod = (pf.mod || []).map(x => x.name);
    const up = (pf.up || []).map(x => x.name);
    const names = [].concat(mod.slice(0, 4), up.slice(0, 2));
    while (names.length < 6) names.push('通用能力');
    return names.slice(0, 6).map(n => {
      const h = nameHash(n);
      const score = 60 + (h % 37); // 60~96
      return { name: n, score };
    });
  }

  // 纯构建函数：根据配置生成雷达图 SVG 字符串（数据与样式保持一致，仅尺寸可配置）
  function buildRadarSVG(opts) {
    const { SIZE, RMAX_R = 0.28, MAX_LINE_PX, LINE_H, FONT, strokeW = 1.6 } = opts;
    const axes = getRadarAxes();
    const N = 6;
    const cx = SIZE / 2, cy = SIZE / 2;
    const RMAX = SIZE * RMAX_R;
    const RINGS = 4;
    const ang = i => (-Math.PI / 2) + (i * 2 * Math.PI / N); // 顶点从正上方开始
    const pt = (i, r) => [cx + r * Math.cos(ang(i)), cy + r * Math.sin(ang(i))];

    // 把长技能名按"接近等宽"切成多行（不省略、不缩字）
    const CHAR_W_CN = FONT * 0.95, CHAR_W_EN = FONT * 0.52;
    function wrapLabel(name, maxPx) {
      const w = ch => /[一-鿿　-〿＀-￯]/.test(ch) ? CHAR_W_CN : CHAR_W_EN;
      let total = 0, line = '', lines = [];
      for (const ch of name) {
        const cw = w(ch);
        if (total + cw > maxPx && line) { lines.push(line); line = ch; total = cw; }
        else { line += ch; total += cw; }
      }
      if (line) lines.push(line);
      return lines.length ? lines : [name];
    }

    // 背景网格（同心多边形）
    let grid = '';
    for (let ring = 1; ring <= RINGS; ring++) {
      const r = RMAX * ring / RINGS;
      const pts = axes.map((_, i) => pt(i, r).map(v => v.toFixed(1)).join(',')).join(' ');
      grid += `<polygon points="${pts}" fill="none" stroke="rgba(255,255,255,0.10)" stroke-width="1"/>`;
    }
    // 轴线 + 多行标签（左右两侧贴边，文本右/左对齐）
    let axis = '';
    axes.forEach((ax, i) => {
      const [x, y] = pt(i, RMAX);
      axis += `<line x1="${cx}" y1="${cy}" x2="${x.toFixed(1)}" y2="${y.toFixed(1)}" stroke="rgba(255,255,255,0.14)" stroke-width="1"/>`;
      const a = ang(i);
      const lx = cx + (RMAX + 14) * Math.cos(a) + (Math.cos(a) > 0.05 ? 6 : (Math.cos(a) < -0.05 ? -6 : 0));
      const ly = cy + (RMAX + 14) * Math.sin(a);
      let anchor = 'middle';
      if (Math.cos(a) < -0.05) anchor = 'end';
      else if (Math.cos(a) > 0.05) anchor = 'start';
      const lines = wrapLabel(ax.name, MAX_LINE_PX);
      const baseY = ly + 3 - (lines.length - 1) * LINE_H / 2;
      const tspans = lines.map((ln, k) =>
        `<tspan x="${lx.toFixed(1)}" dy="${k === 0 ? 0 : LINE_H}">${escape(ln)}</tspan>`
      ).join('');
      axis += `<text class="ir-radar-axis" x="${lx.toFixed(1)}" y="${baseY.toFixed(1)}" text-anchor="${anchor}" font-size="${FONT}">${tspans}</text>`;
    });
    // 数据多边形
    const dataPts = axes.map((ax, i) => pt(i, RMAX * ax.score / 100).map(v => v.toFixed(1)).join(',')).join(' ');
    let data = `<polygon points="${dataPts}" fill="rgba(31,200,217,0.22)" stroke="#1FC8D9" stroke-width="${strokeW}" stroke-linejoin="round"/>`;
    axes.forEach((ax, i) => {
      const [x, y] = pt(i, RMAX * ax.score / 100);
      data += `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${strokeW * 1.5}" fill="#1FC8D9" stroke="#0a0f17" stroke-width="0.8"/>`;
    });

    return `<svg viewBox="0 0 ${SIZE} ${SIZE}" preserveAspectRatio="xMidYMid meet" role="img" aria-label="核心技能掌握度雷达图">
        ${grid}${axis}${data}
      </svg>`;
  }

