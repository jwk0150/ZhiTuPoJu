    // 技能名 hash → 0~1（保证同一技能每次打开弹层内容稳定，但不同技能之间差异显著）
    function nameHash(name) {
      let h = 0; for (let i = 0; i < name.length; i++) h = ((h << 5) - h + name.charCodeAt(i)) | 0;
      return Math.abs(h);
    }
    // 基于 hash 选取数组项，避免同一技能每次刷新内容漂移
    function pick(arr, name, offset = 0) {
      return arr[(nameHash(name) + offset) % arr.length];
    }
    // 基于 hash 拼装百分比 / 数字数据
    function pickNum(name, min, max, salt = 0) {
      const h = (nameHash(name) + salt) % 1000;
      return Math.round(min + (h / 1000) * (max - min));
    }

