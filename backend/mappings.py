def categorize_job(title: str) -> str:
    """根据岗位标题返回类别"""
    if not title:
        return "其他"
    for cat, keywords in JOB_CATEGORY_RULES:
        for kw in keywords:
            if kw in title:
                return cat
    return "其他"


def parse_city_to_province(city: str) -> str | None:
    """从 "城市·区县" 格式解析出省份"""
    if not city:
        return None
    # 去掉区县部分
    main_city = city.split("·")[0].strip()
    return CITY_TO_PROVINCE.get(main_city)
